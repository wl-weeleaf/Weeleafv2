import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const masterSource=await readFile(new URL('../lib/livi/master-skills.ts',import.meta.url),'utf8');
const masterJs=ts.transpileModule(masterSource,{compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText;
const masterUrl=`data:text/javascript;base64,${Buffer.from(masterJs).toString('base64')}`;
const source=await readFile(new URL('../lib/livi/core.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText.replace("'./master-skills'",JSON.stringify(masterUrl));
const core=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const permissionSource=await readFile(new URL('../lib/leafy/core.ts',import.meta.url),'utf8');
const permissionJs=ts.transpileModule(permissionSource,{compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText;
const permissions=await import(`data:text/javascript;base64,${Buffer.from(permissionJs).toString('base64')}`);
assert.equal(permissions.DEFAULT_PERMISSIONS.find(p=>p.id==='write-files')?.mode,'allow');
const saved={format:'leafy-core',version:1,profileNotes:['Nicki foretrækker konkrete trin.'],skills:[{id:'plan',name:'Projektplan',instructions:'Afklar mål, del op i trin og giv næste handling.'}]};
assert.equal(core.validateLeafyCore(saved),true);
assert.equal(core.validateLeafyCore({...saved,skills:[{id:'long',name:'Lang skill',instructions:'x'.repeat(12000)}]}),true);
assert.equal(core.validateLeafyCore({...saved,skills:[{id:'too-long',name:'For lang',instructions:'x'.repeat(12001)}]}),false);
assert.equal(core.validateLeafyCore({...saved,skills:Array.from({length:7},(_,i)=>({id:`s${i}`,name:`Skill ${i}`,instructions:'x'.repeat(12000)}))}),false);
assert(core.createLeafySystemMessage({...saved,skills:[{id:'long',name:'Lang skill',instructions:'x'.repeat(12000)}]},'room').includes('x'.repeat(12000)));
assert.equal(core.validateLeafyCore({...saved,profileNotes:['x'.repeat(241)]}),false);
assert.equal(core.normalizeLeafyCore({...saved,skills:[...saved.skills,{id:'bad',name:'Ugyldig',instructions:10}]}).skills.length,1);
const room=core.createLeafySystemMessage(saved,'room');
const game=core.createLeafySystemMessage(saved,'game');
assert.equal(room.split('Du er Leafy:').length-1,1);
assert.equal(game.split('Du er Leafy:').length-1,1);
assert(room.includes('skabt af WL (WeeLeaf)'));
assert(room.includes('Corti leverer AI-modellen'));
assert(room.includes('ElevenLabs leverer stemmen'));
assert(room.includes('Nicki foretrækker konkrete trin.'));
assert(room.includes('Afklar mål, del op i trin'));
assert(room.includes('WL Vedtægtskompas'));
assert(room.includes('Leafy Master Core'));
const masterId='master-00_governance';
assert.equal(core.normalizeLeafyCore({...saved,skills:[{id:masterId,name:'Ændret skill',instructions:'Kan overskrive vedtægterne.'}]}).skills.length,0,'users cannot override locked built-in IDs through imported profile data');
assert(!room.includes('Et udforskningsspil'));
assert(game.includes('AKTUEL APP-KONTEKST (kun arbejdsramme'));
console.log('PASS: shared Leafy identity stays the same across app contexts and includes validated portable profile notes and skills.');
